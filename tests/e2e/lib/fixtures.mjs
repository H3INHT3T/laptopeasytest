export function assertSwissPalette(paletteResult) {
  assert.ok(paletteResult && typeof paletteResult === "object", "assertSwissPalette requires a paletteResult object or array");

  if (Array.isArray(paletteResult)) {
    const bad = [];
    for (const entry of paletteResult) {
      if (typeof entry === "string") {
        // Basic hex/rgb string check
        const m = entry.match(/^#([0-9a-f]{6})$/i);
        if (m) {
          const r = parseInt(m[1].slice(0, 2), 16);
          const g = parseInt(m[1].slice(2, 4), 16);
          const b = parseInt(m[1].slice(4, 6), 16);
          if (!isSwissRgb(r, g, b)) {
            bad.push({ rawColor: entry, rgb: [r, g, b] });
          }
        }
      } else if (entry && Array.isArray(entry.rgb)) {
        const [r, g, b] = entry.rgb;
        if (!isSwissRgb(r, g, b)) {
          bad.push(entry);
        }
      } else if (entry && entry.rawColor) {
        bad.push(entry);
      }
    }
    assert.equal(
      bad.length,
      0,
      `Swiss Precision Light palette violations detected (${bad.length}): ${JSON.stringify(bad.slice(0, 8))}`
    );
    return;
  }

  const violations = Array.isArray(paletteResult.violations) ? paletteResult.violations : [];
  assert.equal(
    paletteResult.ok === true && violations.length === 0,
    true,
    `Swiss Precision Light palette violations (${violations.length}/${paletteResult.totalChecked ?? "?"}): ${JSON.stringify(
      violations.slice(0, 8)
    )}`
  );
}

function isSwissRgb(r, g, b) {
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  if (max - min <= 18) return true;
  if (b > r && b >= g) {
    const d = max - min;
    const rn = r / 255;
    const gn = g / 255;
    const bn = b / 255;
    const maxN = max / 255;
    const dN = d / 255;
    let hue = 0;
    if (dN > 0) {
      if (maxN === bn) hue = ((rn - gn) / dN + 4) * 60;
      else if (maxN === gn) hue = ((bn - rn) / dN + 2) * 60;
      else hue = (((gn - bn) / dN) % 6) * 60;
      if (hue < 0) hue += 360;
    }
    if (hue >= 195 && hue <= 250) return true;
  }
  return false;
}

